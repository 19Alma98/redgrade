_BLANK = _GLYPHS[" "]


def glyph(char: str) -> tuple[str, ...]:
    """Seven rows of five cells (``#`` on, ``.`` off) for ``char``."""
    return _GLYPHS.get(char.upper(), _BLANK)


def raster(text: str, *, spacing: int = 1) -> list[list[bool]]:
    """One line of text as a bitmap: ``GLYPH_HEIGHT`` rows of on/off cells."""
    rows: list[list[bool]] = [[] for _ in range(GLYPH_HEIGHT)]
    for i, char in enumerate(text):
        cells = glyph(char)
        for y in range(GLYPH_HEIGHT):
            if i:
                rows[y].extend([False] * spacing)
            rows[y].extend(c == "#" for c in cells[y])
    return rows


def ascii_art(word: str, *, on: str = "#", off: str = " ") -> str:
    """``word`` drawn with ``on`` / ``off`` characters, one text line per bitmap row."""
    return "\n".join("".join(on if cell else off for cell in row).rstrip() for row in raster(word, spacing=2))
